    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
        Empleado emp = new Empleado();
        emp.nom_usr = jtUsuario.getText().trim();
        emp.nip = new String(jpNip.getPassword()).trim();

        if (emp.nom_usr.isEmpty() || emp.nip.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escribe tu usuario y tu NIP");
            return;
        }

        if (emp.acceder(cnx.getCon()) != 1) {
            JOptionPane.showMessageDialog(this, "No se pudo entrar: " + emp.error);
            return;
        }

        if (emp.puesto.equals("Administrador")) {
            FAdmin ven = new FAdmin();
            ven.ObtenerConexion(cnx, emp.codigo, emp.nombre);
            abrir(ven);
        } else if (emp.puesto.equals("Mesero")) {
            FMesero ven = new FMesero();
            ven.ObtenerConexion(cnx, emp.codigo, emp.nombre);
            abrir(ven);
        } else if (emp.puesto.equals("Cocinero")) {
            FCocinero ven = new FCocinero();
            ven.ObtenerConexion(cnx, emp.codigo, emp.nombre);
            abrir(ven);
        } else if (emp.puesto.equals("Cajero")) {
            FCajero ven = new FCajero();
            ven.ObtenerConexion(cnx, emp.codigo, emp.nombre);
            abrir(ven);
        } else {
            JOptionPane.showMessageDialog(this, "El puesto " + emp.puesto + " no tiene acceso al sistema");
        }
    }//GEN-LAST:event_btnEntrarActionPerformed

