    public void Limpiar() {
        jtNombre.setText("");
        jtDescripcion.setText("");
        jtPrecio.setText("");
        jcCategoria.setSelectedIndex(0);
        jcEstado.setSelectedIndex(0);
        LFoto.setIcon(null);
        foto = null;
        idalimento = 0;
        TConsultas.clearSelection();
        jtNombre.requestFocus();
    }

    // Lee los campos y regresa el alimento, o null si hay un dato incorrecto
    private Alimento LeerAlimento() {
        String nom = jtNombre.getText().trim();
        String des = jtDescripcion.getText().trim();
        if (nom.isEmpty() || des.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escribe el nombre y la descripción del alimento");
            return null;
        }
        float pre;
        try {
            pre = Float.parseFloat(jtPrecio.getText().trim());
            if (pre <= 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Escribe un precio válido");
            return null;
        }
        return new Alimento(idalimento, nom, des, pre, foto, jcCategoria.getSelectedItem().toString(),
                jcEstado.getSelectedItem().toString());
    }

