    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        if (!HayDatos()) {
            return;
        }
        String obs = jtObservaciones.getText().trim();
        if (obs.isEmpty()) {
            obs = "N/A";
        }

        Orden ord = new Orden(0, cnx.ObtenerFechaHora().substring(0, 19), obs, "Ordenado",
                Integer.parseInt(jcSilla.getSelectedItem().toString()), Conexion.codigoCombo(jcCliente),
                Integer.parseInt(jcMesa.getSelectedItem().toString()),
                Integer.parseInt(Conexion.codigoCombo(jcAlimento)), codigoMesero, null);

        if (ord.insertar(cnx.getCon()) == 1) {
            JOptionPane.showMessageDialog(this, "Orden Registrada");
            Consultar();
            Limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar la orden\n" + ord.error);
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        if (jtFolio.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Selecciona una orden de la tabla");
            return;
        }
        if (!HayDatos()) {
            return;
        }
        String actual = cnx.buscarDato("ordenes", "estadoo", "folio", jtFolio.getText());
        if (!actual.equals("Ordenado")) {
            JOptionPane.showMessageDialog(this, "Solo se puede modificar una orden en estado Ordenado");
            return;
        }
        String obs = jtObservaciones.getText().trim();
        if (obs.isEmpty()) {
            obs = "N/A";
        }

        Orden ord = new Orden(Integer.parseInt(jtFolio.getText()), null, obs, null,
                Integer.parseInt(jcSilla.getSelectedItem().toString()), Conexion.codigoCombo(jcCliente),
                Integer.parseInt(jcMesa.getSelectedItem().toString()),
                Integer.parseInt(Conexion.codigoCombo(jcAlimento)), null, null);

        if (ord.modificar(cnx.getCon()) == 1) {
            JOptionPane.showMessageDialog(this, "Orden Modificada");
            Consultar();
            Limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo modificar la orden\n" + ord.error);
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnCancelarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarActionPerformed
        if (jtFolio.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Selecciona una orden de la tabla");
            return;
        }
        String actual = cnx.buscarDato("ordenes", "estadoo", "folio", jtFolio.getText());
        if (!Orden.puedeCambiar(actual, "Cancelar")) {
            JOptionPane.showMessageDialog(this, "La orden está en estado " + actual + ", ya no se puede cancelar");
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "¿Cancelar la orden " + jtFolio.getText() + "?", "Cancelar",
                JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) {
            return;
        }

        Orden ord = new Orden();
        ord.folio = Integer.parseInt(jtFolio.getText());
        ord.estadoo = "Cancelar";
        if (ord.cambiarEstado(cnx.getCon()) == 1) {
            JOptionPane.showMessageDialog(this, "Orden Cancelada");
            Consultar();
            Limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo cancelar la orden\n" + ord.error);
        }
    }//GEN-LAST:event_btnCancelarActionPerformed

