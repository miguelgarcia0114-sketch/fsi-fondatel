    public void Limpiar() {
        jtNumero.setText("");
        jtCapacidad.setText("");
        jcEstado.setSelectedIndex(0);
        TConsultas.clearSelection();
        jtNumero.requestFocus();
    }

    // Lee los campos y regresa la mesa, o null si hay un dato incorrecto
    private Mesa LeerMesa() {
        try {
            int numero = Integer.parseInt(jtNumero.getText().trim());
            int capacidad = Integer.parseInt(jtCapacidad.getText().trim());
            if (numero <= 0 || capacidad <= 0) {
                throw new NumberFormatException();
            }
            return new Mesa(numero, jcEstado.getSelectedItem().toString(), capacidad);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Escribe el número y la capacidad (número de sillas) de la mesa");
            return null;
        }
    }

