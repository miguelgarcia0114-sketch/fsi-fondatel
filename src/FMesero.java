    private void btnCambiarEstadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCambiarEstadoActionPerformed
        if (jtFolio.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Selecciona una orden de la tabla");
            return;
        }
        String nuevo = jcEstado.getSelectedItem().toString();
        String actual = cnx.buscarDato("ordenes", "estadoo", "folio", jtFolio.getText());
        if (!Orden.puedeCambiar(actual, nuevo)) {
            JOptionPane.showMessageDialog(this, "La orden está en estado " + actual + ", no se puede cambiar a " + nuevo);
            return;
        }

        Orden ord = new Orden();
        ord.folio = Integer.parseInt(jtFolio.getText());
        ord.estadoo = nuevo;
        if (ord.cambiarEstado(cnx.getCon()) == 1) {
            Consultar();
            Limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo cambiar el estado\n" + ord.error);
        }
    }//GEN-LAST:event_btnCambiarEstadoActionPerformed

