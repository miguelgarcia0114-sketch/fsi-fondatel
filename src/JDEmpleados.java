    private void TConsultasMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TConsultasMousePressed
        int ren = TConsultas.getSelectedRow();
        DefaultTableModel modelo = (DefaultTableModel) TConsultas.getModel();

        if (ren >= 0) {
            String codigo = modelo.getValueAt(ren, 0).toString();
            jtCodigo.setText(codigo);
            jtNombre.setText(modelo.getValueAt(ren, 1).toString());
            jcPuesto.setSelectedItem(modelo.getValueAt(ren, 2).toString());
            jcTurno.setSelectedItem(modelo.getValueAt(ren, 3).toString());
            jtUsuario.setText(modelo.getValueAt(ren, 4).toString());
            jtNip.setText(cnx.buscarDato("empleados", "nip", "codigo", codigo));
            jcEstado.setSelectedItem(modelo.getValueAt(ren, 5).toString());
        }
    }//GEN-LAST:event_TConsultasMousePressed

