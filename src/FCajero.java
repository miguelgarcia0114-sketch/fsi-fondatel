    // Órdenes que todavía no se pagan, de la mesa elegida
    public void Consultar() {
        String sql = "SELECT o.folio, o.fecha_hora, o.mesas_numero AS mesa, o.silla, a.nombrea AS alimento, a.precio, o.estadoo AS estado "
                + "FROM ordenes o "
                + "INNER JOIN alimentos a ON a.idalimentos = o.alimentos_idalimentos "
                + "WHERE o.estadoo NOT IN ('Pagado', 'Cancelar')";
        if (!jcMesa.getSelectedItem().toString().equals("Todos")) {
            sql += " AND o.mesas_numero = " + jcMesa.getSelectedItem().toString();
        }
        sql += " ORDER BY o.mesas_numero, o.silla, o.folio";
        cnx.entablar(sql, TConsultas, 8, 22, 8, 8, 28, 12, 14);
        LTotal.setText("Total a cobrar: $0.00");
    }

