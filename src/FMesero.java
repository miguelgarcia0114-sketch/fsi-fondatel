    public void ObtenerConexion(Conexion cnx, String codigo, String nombre) {
        this.cnx = cnx;
        codigoMesero = codigo;
        jlDerecha.setText("Mesero: " + nombre);

        cnx.llenarCombo("SELECT numero FROM mesas ORDER BY numero", jcMesa);
        cnx.llenarCombo("SELECT codigoc, nombrec FROM clientes ORDER BY nombrec", jcCliente);
        cnx.llenarCombo("SELECT idalimentos, nombrea FROM alimentos WHERE estadoa = 'Disponible' ORDER BY nombrea", jcAlimento);
        LlenarSillas();
        Consultar();
    }

    // Las sillas de la lista dependen de la capacidad de la mesa elegida
    public void LlenarSillas() {
        jcSilla.removeAllItems();
        if (jcMesa.getSelectedItem() == null) {
            return;
        }
        String cap = cnx.buscarDato("mesas", "capacidad", "numero", jcMesa.getSelectedItem().toString());
        int sillas = cap.isEmpty() ? 0 : Integer.parseInt(cap);
        for (int i = 1; i <= sillas; i++) {
            jcSilla.addItem(String.valueOf(i));
        }
    }

    // Órdenes que siguen en proceso
    public void Consultar() {
        cnx.entablar("SELECT o.folio, o.fecha_hora, o.mesas_numero AS mesa, o.silla, c.nombrec AS cliente, "
                + "a.nombrea AS alimento, o.observaciones, o.estadoo AS estado "
                + "FROM ordenes o "
                + "INNER JOIN clientes c ON c.codigoc = o.clientes_codigoc "
                + "INNER JOIN alimentos a ON a.idalimentos = o.alimentos_idalimentos "
                + "WHERE o.estadoo NOT IN ('Pagado', 'Cancelar') "
                + "ORDER BY o.folio DESC", TConsultas, 8, 20, 8, 8, 16, 16, 14, 10);
    }

    public void Limpiar() {
        jtFolio.setText("");
        jtObservaciones.setText("");
        if (jcMesa.getItemCount() > 0) {
            jcMesa.setSelectedIndex(0);
        }
        if (jcCliente.getItemCount() > 0) {
            jcCliente.setSelectedIndex(0);
        }
        if (jcAlimento.getItemCount() > 0) {
            jcAlimento.setSelectedIndex(0);
        }
        jcEstado.setSelectedIndex(0);
        TConsultas.clearSelection();
    }

    // Revisa que haya mesa, silla, cliente y alimento elegidos
    private boolean HayDatos() {
        if (jcMesa.getSelectedItem() == null || jcSilla.getSelectedItem() == null
                || jcCliente.getSelectedItem() == null || jcAlimento.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Elige la mesa, la silla, el cliente y el alimento");
            return false;
        }
        return true;
    }

