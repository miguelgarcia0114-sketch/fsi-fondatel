    private void btnCobrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCobrarActionPerformed
        int[] seleccion = TConsultas.getSelectedRows();
        if (seleccion.length == 0) {
            JOptionPane.showMessageDialog(this, "Selecciona las órdenes que se van a cobrar");
            return;
        }

        int cobradas = 0;
        double total = 0;
        for (int ren : seleccion) {
            // solo se cobran las órdenes que ya fueron entregadas
            if (TConsultas.getValueAt(ren, COL_ESTADO).toString().equals("Entregado")) {
                Orden ord = new Orden();
                ord.folio = Integer.parseInt(TConsultas.getValueAt(ren, 0).toString());
                ord.estadoo = "Pagado";
                if (ord.cambiarEstado(cnx.getCon()) == 1) {
                    cobradas++;
                    total += Double.parseDouble(TConsultas.getValueAt(ren, COL_PRECIO).toString());
                } else {
                    JOptionPane.showMessageDialog(this, "No se pudo cobrar la orden " + ord.folio + "\n" + ord.error);
                }
            }
        }

        if (cobradas == 0) {
            JOptionPane.showMessageDialog(this, "Solo se pueden cobrar órdenes en estado Entregado");
        } else {
            JOptionPane.showMessageDialog(this, "Órdenes cobradas: " + cobradas + "\nTotal: $" + String.format("%.2f", total));
            Consultar();
        }
    }//GEN-LAST:event_btnCobrarActionPerformed

    private void TConsultasMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TConsultasMousePressed
        // suma el precio de las órdenes seleccionadas que ya se entregaron
        double total = 0;
        for (int ren : TConsultas.getSelectedRows()) {
            if (TConsultas.getValueAt(ren, COL_ESTADO).toString().equals("Entregado")) {
                total += Double.parseDouble(TConsultas.getValueAt(ren, COL_PRECIO).toString());
            }
        }
        LTotal.setText("Total a cobrar: $" + String.format("%.2f", total));
    }//GEN-LAST:event_TConsultasMousePressed

