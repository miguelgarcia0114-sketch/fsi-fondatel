    private void btnAbrirFotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirFotoActionPerformed
        JFileChooser fc = new JFileChooser(System.getProperty("user.dir"));
        if (fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            File archivo = fc.getSelectedFile();
            try {
                // ImageIO valida que sea un PNG/JPG/GIF real (ImageIcon falla en silencio)
                java.awt.image.BufferedImage img = javax.imageio.ImageIO.read(archivo);
                if (img == null) {
                    JOptionPane.showMessageDialog(this,
                            "No se pudo leer la imagen.\n"
                            + "Solo se admiten PNG, JPG y GIF. Si el archivo es WebP con extensión .png/.jpg,\n"
                            + "conviértelo a PNG o JPG e inténtalo de nuevo.");
                    return;
                }
                foto = new ImageIcon(img);
                LFoto.setIcon(new ImageIcon(cnx.escalarImagen(foto.getImage(), 188, 118)));
            } catch (java.io.IOException ex) {
                JOptionPane.showMessageDialog(this, "Error al abrir la imagen: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnAbrirFotoActionPerformed

    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        Alimento ali = LeerAlimento();
        if (ali == null) {
            return;
        }
        if (foto == null) {
            JOptionPane.showMessageDialog(this, "Selecciona primero una foto con ABRIR FOTO");
            return;
        }

        if (ali.insertar(cnx) == 1) {
            JOptionPane.showMessageDialog(this, "Alimento Registrado");
            Consultar();
            Limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar: " + ali.error);
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        if (idalimento == 0) {
            JOptionPane.showMessageDialog(this, "Selecciona un alimento de la tabla");
            return;
        }
        Alimento ali = LeerAlimento();
        if (ali == null) {
            return;
        }

        if (ali.modificar(cnx) == 1) {
            JOptionPane.showMessageDialog(this, "Alimento Modificado");
            Consultar();
            Limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo modificar: " + ali.error);
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        if (idalimento == 0) {
            JOptionPane.showMessageDialog(this, "Selecciona un alimento de la tabla");
            return;
        }

        if (JOptionPane.showConfirmDialog(this, "¿Borrar el alimento " + jtNombre.getText() + "?", "Borrar",
                JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) {
            return;
        }

        Alimento ali = new Alimento();
        ali.idalimentos = idalimento;
        if (ali.borrar(cnx.getCon()) == 1) {
            JOptionPane.showMessageDialog(this, "Alimento Borrado");
            Consultar();
            Limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo borrar: " + ali.error);
        }
    }//GEN-LAST:event_btnBorrarActionPerformed

