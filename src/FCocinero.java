    public void Consultar() {
        cnx.entablar("SELECT o.folio, o.fecha_hora, o.mesas_numero AS mesa, o.silla, a.nombrea AS alimento, "
                + "o.observaciones, o.estadoo AS estado "
                + "FROM ordenes o "
                + "INNER JOIN alimentos a ON a.idalimentos = o.alimentos_idalimentos "
                + "WHERE o.estadoo IN ('Ordenado', 'Preparando') "
                + "ORDER BY o.fecha_hora", TConsultas, 8, 22, 8, 8, 22, 22, 10);
    }

