    private void TConsultasMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TConsultasMousePressed
        int ren = TConsultas.getSelectedRow();

        if (ren >= 0) {
            String folio = TConsultas.getValueAt(ren, 0).toString();
            ArrayList<ArrayList<String>> datos = cnx.consultar("SELECT mesas_numero, silla, clientes_codigoc, "
                    + "alimentos_idalimentos, observaciones FROM ordenes WHERE folio = " + folio);
            if (!datos.isEmpty()) {
                ArrayList<String> orden = datos.get(0);
                jtFolio.setText(folio);
                jcMesa.setSelectedItem(orden.get(0));
                jcSilla.setSelectedItem(orden.get(1));
                Conexion.seleccionarCodigo(jcCliente, orden.get(2));
                Conexion.seleccionarCodigo(jcAlimento, orden.get(3));
                jtObservaciones.setText(orden.get(4));
            }
        }
    }//GEN-LAST:event_TConsultasMousePressed

