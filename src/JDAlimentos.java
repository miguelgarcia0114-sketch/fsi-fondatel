    private void TConsultasMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TConsultasMousePressed
        int ren = TConsultas.getSelectedRow();
        DefaultTableModel modelo = (DefaultTableModel) TConsultas.getModel();

        if (ren >= 0) {
            idalimento = Integer.parseInt(modelo.getValueAt(ren, 0).toString());
            foto = null; // la foto de la base de datos se conserva si no se elige otra
            LFoto.setIcon(new ImageIcon(cnx.escalarImagen(((ImageIcon) modelo.getValueAt(ren, 1)).
                    getImage(), 188, 118)));
            jtNombre.setText(modelo.getValueAt(ren, 2).toString());
            jtDescripcion.setText(modelo.getValueAt(ren, 3).toString());
            jtPrecio.setText(modelo.getValueAt(ren, 4).toString());
            jcCategoria.setSelectedItem(modelo.getValueAt(ren, 5).toString());
            jcEstado.setSelectedItem(modelo.getValueAt(ren, 6).toString());
        }
    }//GEN-LAST:event_TConsultasMousePressed

